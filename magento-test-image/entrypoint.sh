#!/bin/sh
# Generates /etc/msmtprc from SMTP_* env vars (if present), then hands off
# to the configured CMD. Called by Docker ENTRYPOINT.
#
# Expected env vars (all required when SMTP_HOST is set, except as noted):
#   SMTP_HOST        smtp.tem.scw.cloud
#   SMTP_PORT        2587
#   SMTP_USERNAME    <auth user>                optional — anonymous if unset
#   SMTP_PASSWORD    <auth secret>              optional — paired with USERNAME
#   SMTP_FROM        noreply@example.com        default From: address
#   SMTP_AUTH        login | plain | cram-md5   default: login (only used
#                                                when SMTP_USERNAME is set)
#   SMTP_TLS         starttls | tls | off       default: starttls
#
# If SMTP_USERNAME is unset or empty, the generated msmtprc omits the
# `auth`, `user`, and `password` lines entirely. msmtp then connects
# without authenticating, which mailpit and IP-allowlisted relays
# (Postmark, AWS SES with sender authorization) accept.
#
# If SMTP_HOST is unset, msmtp is still installed but has no usable
# config; Magento email sends will fail at dispatch time. That's a
# valid state for dev instances that don't need email.

set -eu

if [ -n "${SMTP_HOST:-}" ]; then
    SMTP_PORT="${SMTP_PORT:-587}"
    SMTP_AUTH="${SMTP_AUTH:-login}"
    SMTP_TLS_MODE="${SMTP_TLS:-starttls}"

    case "${SMTP_TLS_MODE}" in
        starttls) TLS_ON=on ; STARTTLS_ON=on  ;;
        tls)      TLS_ON=on ; STARTTLS_ON=off ;;
        off)      TLS_ON=off; STARTTLS_ON=off ;;
        *)        echo "entrypoint: unknown SMTP_TLS=${SMTP_TLS_MODE}" >&2; exit 1 ;;
    esac

    umask 077
    cat > /etc/msmtprc <<EOF
# Generated by /usr/local/bin/entrypoint.sh from SMTP_* env vars.
# Do not edit in place — changes are overwritten on every pod restart.
defaults
tls                 ${TLS_ON}
tls_starttls        ${STARTTLS_ON}
tls_trust_file      /etc/ssl/certs/ca-certificates.crt
logfile             /dev/stderr

account             default
host                ${SMTP_HOST}
port                ${SMTP_PORT}
from                ${SMTP_FROM:-noreply@localhost}
EOF
    if [ -n "${SMTP_USERNAME:-}" ]; then
        cat >> /etc/msmtprc <<EOF
auth                ${SMTP_AUTH}
user                ${SMTP_USERNAME}
password            ${SMTP_PASSWORD:-}
EOF
        AUTH_DESC="auth=${SMTP_AUTH}"
    else
        AUTH_DESC="auth=anonymous"
    fi
    chmod 644 /etc/msmtprc
    # www-data (php-fpm user) needs to read the config. 644 is acceptable
    # because the pod already has the password in env vars — the file
    # doesn't widen the exposure.
    echo "entrypoint: wrote /etc/msmtprc for host=${SMTP_HOST} port=${SMTP_PORT} tls=${SMTP_TLS_MODE} ${AUTH_DESC}"
else
    echo "entrypoint: SMTP_HOST unset; Magento email delivery will fail until it's set"
fi

exec "$@"
