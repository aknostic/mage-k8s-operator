// nginxConfigHashAnnotation is the per-workload pod-template annotation
// that triggers a rolling restart when the `<store>-nginx-conf`
// ConfigMap content changes. ADR 007 specifies the SHA-256-of-data
// shape; the value is hex-encoded so it round-trips safely through
// kubectl / API server label/annotation handling.
const nginxConfigHashAnnotation = "mage.aknostic.com/nginx-config-hash"

// ensureNginxConfig materialises the `<store>-nginx-conf` ConfigMap
// per ADR 007 and returns the SHA-256 hash of its data so
// ensureWorkloads can stamp it on each workload Deployment's pod
// template. The hash drives rollout-on-change: a `spec.stores` edit
// rewrites `stores.conf`, recomputes the hash, and triggers a
// rolling restart of every workload.
//
// **Session 2 deferral:** the ConfigMap is generated and the hash is
// emitted, but the ConfigMap is NOT mounted into any workload pod in
// Session 2 — see Slot 22.0 Q3. The reference image
// (`magento-test-image/nginx.conf`) co-hosts nginx + php-fpm with
// inline config and no `include /etc/nginx/conf.d/*.conf;` hook;
// mounting today would be inert. Session 3 lands the mount
// alongside the reference-image contract update (either an nginx
// sidecar per ADR 007 or an `include` hook in the image's nginx.conf).
// Until then this step's value is twofold:
//  1. The CRD→nginx content generator is exercised end-to-end so
//     Session 3 inherits a tested generator and only needs to wire
//     the mount.
//  2. The hash annotation already lands on workload Deployments,
//     so when Session 3's mount appears, the existing pod
//     templates start tracking ConfigMap-content changes
//     automatically — no second rollout required.
//
// The ConfigMap has an `ownerReference` back to the MageStore;
// deleting the MageStore deletes it.
func (r *MageStoreReconciler) ensureNginxConfig(ctx context.Context, store *magev1alpha1.MageStore) (string, error) {
	name := store.Name + "-nginx-conf"
	labels := map[string]string{
		"app.kubernetes.io/name":       "magento",
		"app.kubernetes.io/instance":   store.Name,
		"app.kubernetes.io/managed-by": managedByLabel,
	}

	data := map[string]string{
		"stores.conf":  generateStoresConf(store),
		"default.conf": generateDefaultConf(),
	}

	cm := &corev1.ConfigMap{
		ObjectMeta: metav1.ObjectMeta{Name: name, Namespace: store.Namespace},
	}
	op, err := controllerutil.CreateOrUpdate(ctx, r.Client, cm, func() error {
		cm.Labels = labels
		cm.Data = data
		return ctrl.SetControllerReference(store, cm, r.Scheme)
	})
	if err != nil {
		return "", fmt.Errorf("apply nginx ConfigMap: %w", err)
	}
	if op != controllerutil.OperationResultNone {
		ctrl.LoggerFrom(ctx).Info("nginx config reconciled", "op", string(op))
	}

	return computeNginxConfigHash(data), nil
}

// generateStoresConf emits the two `map $http_host` directives per
// ADR 007. Always emits the map blocks — even when `spec.stores` is
// unset — so the `$MAGE_RUN_CODE` / `$MAGE_RUN_TYPE` variables are
// defined at the http level. This matters because the reference
// image's nginx.conf references both via `fastcgi_param`, and nginx
// errors at config load on undeclared variables. For an unset
// spec.stores, only the `default "";` clause appears, so Magento's
// bootstrap.php receives an empty string and falls back to its
// default store — the least-surprising pre-DNS-cutover shape per
// ADR 007 decision 5. Hosts in the maps preserve the order
// declared in `spec.stores` so generated content is deterministic.
func generateStoresConf(store *magev1alpha1.MageStore) string {
	var b strings.Builder
	b.WriteString("# Generated by mage-operator from spec.stores. Do not edit by hand.\n")
	b.WriteString("# See ADR 007 for the dispatch model and ADR 006 for routing context.\n\n")

	b.WriteString("map $http_host $MAGE_RUN_CODE {\n")
	for _, s := range store.Spec.Stores {
		fmt.Fprintf(&b, "    %s %s;\n", s.Host, s.Code)
	}
	b.WriteString("    default \"\";\n")
	b.WriteString("}\n\n")

	b.WriteString("map $http_host $MAGE_RUN_TYPE {\n")
	for _, s := range store.Spec.Stores {
		fmt.Fprintf(&b, "    %s %s;\n", s.Host, s.Type)
	}
	b.WriteString("    default \"\";\n")
	b.WriteString("}\n")

	return b.String()
}

// generateDefaultConf returns the fastcgi server block per ADR 007.
// Static content (no spec inputs) — every workload gets the same
// fastcgi block, including the two `fastcgi_param MAGE_RUN_CODE` /
// `MAGE_RUN_TYPE` lines that surface the map values into php-fpm's
// `$_SERVER`.
//
// Session 3 may rewrite this when the sidecar architecture lands —
// the exact server-block shape depends on whether the image continues
// to co-host nginx (in which case stores.conf is `include`d at the
// http level and this default.conf is unused) or moves to a separate
// php-fpm-only image (in which case this server block runs in the
// sidecar nginx). Either way the per-request MAGE_RUN_CODE plumbing
// stays the two `fastcgi_param` lines below.
func generateDefaultConf() string {
	return `# Generated by mage-operator. See ADR 007.
# Mount target deferred to Session 3 — see ensure_nginx_config.go header.

server {
    listen 8080;
    server_name _;
    root /app/pub;
    index index.php;

    # Magento's admin response can exceed nginx's default fastcgi
    # buffer; values match Magento's upstream nginx.conf.sample.
    fastcgi_buffer_size 128k;
    fastcgi_buffers 4 256k;
    fastcgi_busy_buffers_size 256k;

    location / {
        try_files $uri $uri/ /index.php?$args;
    }

    location ~ \.php$ {
        fastcgi_pass 127.0.0.1:9000;
        fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
        fastcgi_param MAGE_RUN_CODE $MAGE_RUN_CODE;
        fastcgi_param MAGE_RUN_TYPE $MAGE_RUN_TYPE;
        fastcgi_read_timeout 600s;
        include fastcgi_params;
    }
}
`
}

// computeNginxConfigHash returns the SHA-256 of the ConfigMap's data
// map, hex-encoded. Keys are sorted so the hash is stable across map
// iteration order (Go maps don't preserve insertion order). Each
// key/value is null-byte-delimited so e.g. `{"a": "bc"}` and
// `{"ab": "c"}` hash differently.
func computeNginxConfigHash(data map[string]string) string {
	keys := make([]string, 0, len(data))
	for k := range data {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	h := sha256.New()
	for _, k := range keys {
		h.Write([]byte(k))
		h.Write([]byte{0})
		h.Write([]byte(data[k]))
		h.Write([]byte{0})
	}
	return hex.EncodeToString(h.Sum(nil))
}
